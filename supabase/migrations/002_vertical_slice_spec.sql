-- Migration 002: Vertical Slice Architecture Unified Schema
-- Capacity Blocks, Worker Profiles, and Elastic Storage

-- 1. Worker Profiles (Admin-controlled IAM)
create table if not exists worker_profiles (
  worker_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table worker_profiles enable row level security;

-- 2. Capacity Blocks (Elastic rented warehouse space)
create table if not exists capacity_blocks (
  id uuid primary key default gen_random_uuid(),
  name text,
  pallet_count numeric(8,2) not null check (pallet_count > 0),
  start_date date not null default current_date,
  end_date date not null,
  status text not null default 'active' check (status in ('active', 'expired', 'upcoming')),
  created_at timestamptz not null default now()
);

alter table capacity_blocks enable row level security;

-- Add block_id reference to storage_slots (physical locations linked to capacity blocks)
do $$ 
begin
  if not exists (select 1 from information_schema.columns where table_name = 'storage_slots' and column_name = 'block_id') then
    alter table storage_slots add column block_id uuid references capacity_blocks(id) on delete set null;
  end if;
end $$;

-- 3. Move Tasks (Generated by Lease Expiration Engine)
create table if not exists relocation_tasks (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references items(id) on delete cascade,
  from_slot_id uuid not null references storage_slots(id),
  to_slot_id uuid references storage_slots(id),
  priority text not null default 'high' check (priority in ('low', 'normal', 'high', 'critical')),
  status text not null default 'pending' check (status in ('pending', 'in_progress', 'completed', 'cancelled')),
  reason text not null,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

alter table relocation_tasks enable row level security;
